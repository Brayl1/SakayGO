import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
import { defaultSettings } from "../shared/catalog";
test.beforeEach(async ({ page }) => {
  await page.route("**/api/catalog", (route) => route.fulfill({ json: { ...JSON.parse(readFileSync("public/data/catalog.json", "utf8")), settings: defaultSettings, revision: 0, updatedAt: "2026-11-28" } }));
  await page.route("**/api/session", (route) => route.fulfill({ json: { admin: false, signedIn: false } }));
  await page.route("**/api/fare-policies/current", (route) => route.fulfill({ json: { policies: [] } }));
});
test("floating logo opens an accessible side panel and preserves draft on close", async ({ page }, info) => {
  await page.goto("/");
  const launcher = page.getByRole("button", { name: "Open KaSakay assistant" });
  await expect(launcher).toBeVisible();
  const a = await launcher.boundingBox();
  const b = await page.locator(".hero-route-badge").boundingBox();
  expect(a!.x + a!.width <= b!.x || b!.x + b!.width <= a!.x || a!.y + a!.height <= b!.y || b!.y + b!.height <= a!.y).toBe(true);
  await launcher.click();
  const panel = page.getByRole("dialog", { name: "KaSakay" });
  await expect(panel).toBeVisible();
  await expect(page.getByRole("button", { name: "Close KaSakay assistant" })).toBeFocused();
  await panel.getByLabel("Your message to KaSakay").fill("Centrio to Carmen");
  await page.keyboard.press("Escape");
  await expect(panel).not.toBeVisible();
  await expect(launcher).toBeFocused();
  await launcher.click();
  await expect(panel.getByLabel("Your message to KaSakay")).toHaveValue("Centrio to Carmen");
  await expect(page.getByRole("button", { name: "Close KaSakay assistant" })).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  expect(await panel.evaluate((element) => element.contains(document.activeElement))).toBe(true);
  expect(await panel.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.getByRole("button", { name: "Close KaSakay assistant" }).focus();
  await page.locator(".kasakay-panel-content").evaluate((element) => { element.scrollTop = 0; });
  await page.screenshot({ path: "test-results/kasakay-panel-" + info.project.name + ".png", animations: "disabled" });
  await page.getByRole("button", { name: "Close KaSakay assistant" }).click();
  await expect(page.locator("body")).not.toHaveCSS("overflow", "hidden");
});
test("panel uses existing AI endpoint and closes when opening regular tools", async ({ page }) => {
  await page.route("**/api/kasakay", (route) => route.fulfill({ status: 503, json: { error: "KaSakay AI is temporarily unavailable." } }));
  await page.goto("/planner");
  await page.getByRole("button", { name: "Open KaSakay assistant" }).click();
  const panel = page.getByRole("dialog", { name: "KaSakay" });
  await panel.getByRole("button", { name: "Help me plan a trip" }).click();
  await expect(panel.getByRole("alert")).toContainText("temporarily unavailable");
  await panel.getByRole("link", { name: "Fare guide", exact: false }).click();
  await expect(page).toHaveURL(/\/fares$/);
  await expect(panel).not.toBeVisible();
  await page.goto("/kasakay");
  await expect(page.getByRole("heading", { name: "Ask KaSakay" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Open KaSakay assistant" })).toHaveCount(0);
});
